// One-time setup:  npm run setup
// Installs everything the website needs locally — no Docker:
//   portable Postgres (npm) · backend/.venv (pip) · frontend/node_modules (npm) · backend/.env
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { DB, IS_WIN, LOCAL_DB_URL, ROOT, c, findPython, readEnv, run, usesLocalDb, venvPython } from './lib.mjs';

const BACKEND = path.join(ROOT, 'backend');
const FRONTEND = path.join(ROOT, 'frontend');
const npm = (args, cwd) => run(IS_WIN ? 'npm.cmd' : 'npm', args, { cwd, shell: IS_WIN });

function step(n, text) {
  console.log(`\n${c.bold(c.cyan(`[${n}/5]`))} ${c.bold(text)}`);
}

async function main() {
  step(1, 'Portable PostgreSQL (npm install at the project root)');
  npm(['install', '--no-audit', '--no-fund'], ROOT);

  step(2, 'Back-end Python environment (backend/.venv)');
  const py = venvPython(BACKEND);
  if (!fs.existsSync(py)) {
    const [cmd, ...pre] = findPython();
    run(cmd, [...pre, '-m', 'venv', path.join(BACKEND, '.venv')]);
  }
  run(py, ['-m', 'pip', 'install', '-q', '--upgrade', 'pip']);
  run(py, ['-m', 'pip', 'install', '-q', '-r', path.join(BACKEND, 'requirements-dev.txt')]);
  console.log(c.green('✓ Python packages installed'));

  step(3, 'Front-end packages (frontend/node_modules)');
  npm(['install', '--no-audit', '--no-fund'], FRONTEND);

  step(4, 'Configuration (backend/.env)');
  const envFile = path.join(BACKEND, '.env');
  if (fs.existsSync(envFile)) {
    console.log(c.dim('backend/.env already exists — left unchanged.'));
  } else {
    const env = [
      '# Local development. Generated by `npm run setup`. Never commit this file.',
      'ENVIRONMENT=development',
      `DATABASE_URL=${LOCAL_DB_URL}`,
      'CORS_ORIGINS=http://localhost:5173,http://localhost:4173',
      `JWT_SECRET=${crypto.randomBytes(32).toString('hex')}`,
      `INGEST_API_KEY=dev-${crypto.randomBytes(16).toString('hex')}`,
      'ADMIN_EMAIL=admin@example.com',
      'ADMIN_PASSWORD=ChangeMe-dev-123',
      'LOG_LEVEL=INFO',
      '',
    ].join('\n');
    fs.writeFileSync(envFile, env);
    console.log(c.green('✓ Created backend/.env'));
  }

  step(5, 'Database');
  const { DATABASE_URL } = readEnv(envFile);
  if (usesLocalDb(DATABASE_URL)) {
    const db = await import('./db.mjs');
    await db.start();
    await db.stop();
  } else {
    console.log(c.dim('DATABASE_URL points to an external database (e.g. Neon) — skipping the local one.'));
  }

  const env = readEnv(envFile);
  console.log(`
${c.green(c.bold('Setup complete.'))}

  Start everything:   ${c.bold('npm run dev')}
  Website:            http://localhost:5173
  API docs:           http://localhost:8000/docs
  Admin login:        ${env.ADMIN_EMAIL} / ${env.ADMIN_PASSWORD}   ${c.dim('(edit backend/.env before the first run to change)')}
  Local database:     localhost:${DB.port}  ${c.dim('(data in .devdb/)')}
`);
}

main().catch((e) => {
  console.error(c.red(`\nSetup failed: ${e.message}`));
  process.exit(1);
});
